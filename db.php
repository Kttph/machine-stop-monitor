<?php

/*
|--------------------------------------------------------------------------
| db.php
|--------------------------------------------------------------------------
| ไฟล์สำหรับเชื่อมต่อฐานข้อมูล SQLite
|
| ฐานข้อมูล:
| machine_stop.db
|
| ไฟล์นี้จะถูกเรียกใช้จากหน้า PHP อื่น ๆ
| เช่น index.php, dashboard.php, repair.php
|--------------------------------------------------------------------------
*/


// -------------------------------------------------------------------------
// กำหนดตำแหน่งของไฟล์ฐานข้อมูล
// __DIR__ หมายถึงโฟลเดอร์เดียวกับไฟล์ db.php
// -------------------------------------------------------------------------

$dbFile = __DIR__ . '/machine_stop.db';


// -------------------------------------------------------------------------
// เริ่มเชื่อมต่อฐานข้อมูล
// -------------------------------------------------------------------------

try {

    /*
    | สร้างการเชื่อมต่อ SQLite
    |
    | PDO = PHP Data Objects
    | ใช้สำหรับเชื่อมต่อฐานข้อมูล
    */
    $db = new PDO('sqlite:' . $dbFile);


    // ---------------------------------------------------------------------
    // กำหนดให้ PDO แสดง Error เป็น Exception
    // จะช่วยให้ตรวจสอบปัญหาได้ง่าย
    // ---------------------------------------------------------------------

    $db->setAttribute(
        PDO::ATTR_ERRMODE,
        PDO::ERRMODE_EXCEPTION
    );


    // ---------------------------------------------------------------------
    // กำหนดรูปแบบข้อมูลที่ได้จากฐานข้อมูล
    // ให้สามารถเรียกใช้ชื่อคอลัมน์ได้โดยตรง
    // เช่น $user['username']
    // ---------------------------------------------------------------------

    $db->setAttribute(
        PDO::ATTR_DEFAULT_FETCH_MODE,
        PDO::FETCH_ASSOC
    );


    // ---------------------------------------------------------------------
    // เปิดใช้งาน Foreign Key
    //
    // ใช้ควบคุมความสัมพันธ์ระหว่าง
    // users / machines / problems / repairs
    // ---------------------------------------------------------------------

    $db->exec("PRAGMA foreign_keys = ON");


} catch (PDOException $e) {

    // ---------------------------------------------------------------------
    // ถ้าเชื่อมต่อฐานข้อมูลไม่ได้
    // ให้หยุดการทำงานและแสดงข้อความ Error
    // ---------------------------------------------------------------------

    die(
        "ไม่สามารถเชื่อมต่อฐานข้อมูลได้: "
        . $e->getMessage()
    );

}

?>