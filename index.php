// -------------------------------------------------------------------------
// เริ่มต้น Session
//
// Session ใช้สำหรับจดจำว่าใคร Login อยู่
// -------------------------------------------------------------------------

session_start();


// -------------------------------------------------------------------------
// เรียกใช้ไฟล์เชื่อมต่อฐานข้อมูล
// -------------------------------------------------------------------------

require_once 'db.php';


// -------------------------------------------------------------------------
// ถ้าผู้ใช้ Login อยู่แล้ว
// ไม่จำเป็นต้องกลับมา Login ซ้ำ
// ให้ไปหน้า Dashboard เลย
// -------------------------------------------------------------------------

if (isset($_SESSION['user'])) {

    header("Location: dashboard.php");

    exit;
}


// -------------------------------------------------------------------------
// ตัวแปรสำหรับเก็บข้อความ Error
// -------------------------------------------------------------------------

$error = "";


// -------------------------------------------------------------------------
// ตรวจสอบว่าผู้ใช้กดปุ่ม Login หรือไม่
//
// $_SERVER['REQUEST_METHOD'] === 'POST'
// หมายถึง Form ถูกส่งข้อมูลมาด้วย POST
// -------------------------------------------------------------------------

if ($_SERVER['REQUEST_METHOD'] === 'POST') {


    // ---------------------------------------------------------------------
    // รับ Username จาก Form
    //
    // trim() ใช้ตัดช่องว่างด้านหน้าและด้านหลัง
    // ---------------------------------------------------------------------

    $username = trim($_POST['username'] ?? '');


    // ---------------------------------------------------------------------
    // รับ Password จาก Form
    // ---------------------------------------------------------------------

    $password = $_POST['password'] ?? '';


    // ---------------------------------------------------------------------
    // ตรวจสอบว่ากรอกข้อมูลครบหรือไม่
    // ---------------------------------------------------------------------

    if ($username === '' || $password === '') {

        $error = "กรุณากรอกชื่อผู้ใช้และรหัสผ่าน";

    } else {


        // -----------------------------------------------------------------
        // SQL สำหรับค้นหาผู้ใช้งาน
        //
        // ? คือ Placeholder
        // ช่วยป้องกัน SQL Injection
        // -----------------------------------------------------------------

        $sql = "
            SELECT *
            FROM users
            WHERE username = ?
            AND password = ?
        ";


        // -----------------------------------------------------------------
        // เตรียม SQL
        // -----------------------------------------------------------------

        $stmt = $db->prepare($sql);


        // -----------------------------------------------------------------
        // ส่ง Username และ Password เข้าไปแทน ?
        // -----------------------------------------------------------------

        $stmt->execute([
            $username,
            $password
        ]);


        // -----------------------------------------------------------------
        // ดึงข้อมูลผู้ใช้
        // -----------------------------------------------------------------

        $user = $stmt->fetch();


        // -----------------------------------------------------------------
        // ตรวจสอบว่าพบผู้ใช้หรือไม่
        // -----------------------------------------------------------------

        if ($user) {


            // -------------------------------------------------------------
            // Login สำเร็จ
            //
            // เก็บข้อมูลผู้ใช้ไว้ใน Session
            // -------------------------------------------------------------

            $_SESSION['user'] = [

                'id' => $user['id'],

                'username' => $user['username'],

                'full_name' => $user['full_name']

            ];


            // -------------------------------------------------------------
            // ส่งผู้ใช้ไปหน้า Dashboard
            // -------------------------------------------------------------

            header("Location: dashboard.php");

            exit;


        } else {


            // -------------------------------------------------------------
            // Login ไม่สำเร็จ
            // -------------------------------------------------------------

            $error = "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง";

        }

    }

}

